package recorder

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"syscall"
	"time"

	"github.com/cwebley/trailmix/internal/meeting"
)

func sidecarPath(note meetingNote, kind string) string {
	return strings.TrimSuffix(note.Path, filepath.Ext(note.Path)) + "." + kind + ".md"
}

func artifactMarker(id, kind string) string { return "<!-- trailmix: " + kind + " " + id + " -->\n" }

func artifactLock(ctx context.Context, p paths, id string) (*os.File, error) {
	if !meeting.ValidID(id) {
		return nil, errors.New("invalid meeting ID")
	}
	root := filepath.Join(p.home, "meetings")
	if err := os.MkdirAll(root, 0700); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(filepath.Join(root, id+".artifacts.lock"), os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return nil, err
	}
	for {
		if err := ctx.Err(); err != nil {
			f.Close()
			return nil, err
		}
		err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			return f, nil
		}
		if !errors.Is(err, syscall.EWOULDBLOCK) {
			f.Close()
			return nil, err
		}
		select {
		case <-ctx.Done():
			f.Close()
			return nil, ctx.Err()
		case <-time.After(20 * time.Millisecond):
		}
	}
}

// Never replace an unrelated file or follow a sidecar symlink. Callers hold
// the meeting's artifact lock through their read/modify/atomic-write sequence.
func readArtifact(path, marker string) ([]byte, error) {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("sidecar is not a regular file: %s", path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if !strings.HasPrefix(string(data), marker) {
		return nil, fmt.Errorf("refusing to overwrite an unrecognized sidecar: %s", path)
	}
	return data, nil
}

func timestamp(seconds float64) string {
	s := int(seconds)
	if s >= 3600 {
		return fmt.Sprintf("%02d:%02d:%02d", s/3600, s/60%60, s%60)
	}
	return fmt.Sprintf("%02d:%02d", s/60, s%60)
}

func transcriptMarkdown(snapshot transcriptSnapshot) string {
	var out strings.Builder
	fmt.Fprintf(&out, "%s<!-- trailmix: meeting %s -->\n# Transcript\n\nState: %s. Generated from local finalized passages; do not edit this file.\n\n", artifactMarker(snapshot.MeetingID, "transcript"), snapshot.MeetingID, snapshot.Transcription.State)
	for _, passage := range snapshot.Passages {
		fmt.Fprintf(&out, "## %s–%s · %s\n\nPassage: `%s`\n\n", timestamp(passage.Start), timestamp(passage.End), passage.Track, passage.ID)
		text := passage.Text
		if text == "" {
			text = "(empty final)"
		}
		for _, line := range strings.Split(text, "\n") {
			fmt.Fprintf(&out, "> %s\n", line)
		}
		out.WriteString("\n")
	}
	if len(snapshot.Passages) == 0 {
		out.WriteString("No finalized passages yet.\n\n")
	}
	for _, name := range []string{"microphone", "system"} {
		track := snapshot.Transcription.Tracks[name]
		if track.Error != "" {
			fmt.Fprintf(&out, "%s: %s\n\n", name, track.Error)
		}
		for _, gap := range track.Pending {
			fmt.Fprintf(&out, "Incomplete %s: %s–%s\n\n", name, timestamp(gap.Start), timestamp(gap.End))
		}
	}
	return out.String()
}

func exportTranscript(p paths, note meetingNote) (string, error) {
	if err := validateNote(note); err != nil {
		return "", err
	}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()
	guard, err := artifactLock(ctx, p, note.ID)
	if err != nil {
		return "", err
	}
	defer guard.Close()
	// Read after locking: an older ask snapshot must never replace a newer
	// sidecar published by stop or retry. Ask retains its own evidence snapshot.
	snapshot, err := readTranscript(note.Directory, note.ID)
	if err != nil {
		return "", err
	}
	path := sidecarPath(note, "transcript")
	prior, err := readArtifact(path, artifactMarker(note.ID, "transcript"))
	if err != nil {
		return "", err
	}
	text := transcriptMarkdown(snapshot)
	if string(prior) != text {
		if err := meeting.WriteFile(path, []byte(text)); err != nil {
			return "", err
		}
	}
	return path, nil
}

func exportMeetingTranscript(p paths, id string) error {
	note, err := readMeeting(p, id)
	if err != nil {
		return err
	}
	_, err = exportTranscript(p, note)
	return err
}
